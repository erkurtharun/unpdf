#!/usr/bin/env python3
"""Generate src/parser/cmyk_srgb_data.rs from PDFium's CMYK -> sRGB table.

    python scripts/gen_cmyk_srgb.py <path to core/fxge/dib/cfx_cmyk_to_srgb.cpp>

The table is the one PDFium (BSD-3-Clause, see THIRD-PARTY-NOTICES) uses for `DeviceCMYK`:
9 x 9 x 9 x 9 sample points of the CMYK cube (each ink at 0, 1/8, ... 1), indexed
`729*c + 81*m + 9*y + k`, each an sRGB triple. The generated file is not edited by hand.
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
start = src.index("kCMYK = {{")
end = src.index("}};", start)
triples = re.findall(r"\{\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}", src[start:end])
assert len(triples) == 9 ** 4, len(triples)
rows = []
for i in range(0, len(triples), 6):
    rows.append("    " + " ".join("[%s, %s, %s]," % t for t in triples[i:i + 6]))
out = """// Generated by scripts/gen_cmyk_srgb.py from PDFium's core/fxge/dib/cfx_cmyk_to_srgb.cpp --
// do not edit. Copyright 2014 PDFium Authors, BSD-3-Clause (THIRD-PARTY-NOTICES).

/// sRGB for CMYK sampled on a 9 x 9 x 9 x 9 grid (each ink at 0, 1/8, ... 1), indexed
/// `729 * c + 81 * m + 9 * y + k`.
pub(super) static CMYK_TO_SRGB: [[u8; 3]; 6561] = [
%s
];
""" % "\n".join(rows)
open("src/parser/cmyk_srgb_data.rs", "w", encoding="utf-8", newline="\n").write(out)
print(len(triples), "triples")
